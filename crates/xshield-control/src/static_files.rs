//! Serves the built control console from the table embedded at build time, and
//! adds the security headers to every response (docs/07-console-architecture.md
//! sections 7.2.3 and 7.10.6).

use std::sync::Arc;

use axum::{
    body::{Body, Bytes},
    extract::{Request, State},
    http::{HeaderMap, HeaderName, HeaderValue, Method, StatusCode, Uri, header},
    middleware::Next,
    response::{IntoResponse, Response},
};

use crate::{ControlState, error::ApiError};

/// One file of the built console.
#[derive(Debug, Clone, Copy)]
pub struct ConsoleFile {
    /// The file's path in the console, without a leading slash, such as
    /// `assets/app-abc123.js`.
    pub path: &'static str,
    /// The file's bytes.
    pub bytes: &'static [u8],
}

/// The built console, generated by `build.rs` into `OUT_DIR`. It is empty when the
/// console was not built.
pub static EMBEDDED_CONSOLE: &[ConsoleFile] =
    include!(concat!(env!("OUT_DIR"), "/console_files.rs"));

/// The entry document, served for every path that is a client-side route.
const INDEX: &str = "index.html";
const IMMUTABLE: &str = "public, max-age=31536000, immutable";
const NO_CACHE: &str = "no-cache";
/// The content security policy of the console responses (docs/07 section 7.10.6).
const CONTENT_SECURITY_POLICY: &str = "default-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; frame-ancestors 'none'";

/// Serves the console for every path the API does not match. A path that names a
/// file of the console gets that file. Another path without an extension is a
/// client-side route and gets `index.html`. Paths under `/api` are never served here,
/// and only GET and HEAD are answered.
#[must_use]
// Axum handlers must be async functions, though this one awaits nothing.
#[allow(clippy::unused_async)]
pub async fn serve(State(state): State<Arc<ControlState>>, method: Method, uri: Uri) -> Response {
    let path = uri.path();
    if is_api_path(path) {
        return ApiError::new(StatusCode::NOT_FOUND, "NOT_FOUND").into_response();
    }
    let head = method == Method::HEAD;
    if method != Method::GET && !head {
        return method_not_allowed();
    }
    let console = state.console;
    if let Some(file) = table_key(path).and_then(|key| find(console, key)) {
        return file_response(file, head);
    }
    if last_segment(path).contains('.') {
        return (StatusCode::NOT_FOUND, "not found").into_response();
    }
    match find(console, INDEX) {
        Some(index) => file_response(index, head),
        None => (
            StatusCode::SERVICE_UNAVAILABLE,
            "console assets are not built",
        )
            .into_response(),
    }
}

/// Adds the console's security headers to a response: `nosniff`, no framing, no
/// referrer, the content security policy, and `no-store` on API paths. A header the
/// handler already set is kept as it is.
#[must_use]
pub async fn security_headers(request: Request, next: Next) -> Response {
    let api = is_api_path(request.uri().path());
    let mut response = next.run(request).await;
    let headers = response.headers_mut();
    set_unless_set(headers, header::X_CONTENT_TYPE_OPTIONS, "nosniff");
    set_unless_set(headers, header::X_FRAME_OPTIONS, "DENY");
    set_unless_set(headers, header::REFERRER_POLICY, "no-referrer");
    set_unless_set(
        headers,
        header::CONTENT_SECURITY_POLICY,
        CONTENT_SECURITY_POLICY,
    );
    if api {
        set_unless_set(headers, header::CACHE_CONTROL, "no-store");
    }
    response
}

/// Sets `name` to `value` unless the headers already have it.
fn set_unless_set(headers: &mut HeaderMap, name: HeaderName, value: &'static str) {
    if !headers.contains_key(&name) {
        headers.insert(name, HeaderValue::from_static(value));
    }
}

/// Whether a request path is `/api` or lies under `/api/`.
fn is_api_path(path: &str) -> bool {
    path == "/api" || path.starts_with("/api/")
}

/// The table key of a request path: the path without its leading slash. `None` for
/// a path with a character outside ASCII letters, digits and `. _ - ~ /`, for a `..`,
/// or for an empty segment. Such a path is never looked up.
fn table_key(path: &str) -> Option<&str> {
    let key = path.strip_prefix('/')?;
    let plain = key.bytes().all(|byte| {
        byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'_' | b'-' | b'~' | b'/')
    });
    let segments_ok = key.is_empty() || key.split('/').all(|segment| !segment.is_empty());
    (plain && segments_ok && !key.contains("..")).then_some(key)
}

/// The console file whose path is exactly `key`.
fn find(console: &'static [ConsoleFile], key: &str) -> Option<&'static ConsoleFile> {
    console.iter().find(|file| file.path == key)
}

/// The last segment of a request path: the text after its final slash.
fn last_segment(path: &str) -> &str {
    path.rsplit_once('/').map_or(path, |(_, last)| last)
}

/// The `Content-Type` of a console file, from the extension of its name.
fn content_type(path: &str) -> &'static str {
    let extension = last_segment(path)
        .rsplit_once('.')
        .map(|(_, suffix)| suffix.to_ascii_lowercase());
    match extension.as_deref() {
        Some("html") => "text/html; charset=utf-8",
        Some("js" | "mjs") => "text/javascript; charset=utf-8",
        Some("css") => "text/css; charset=utf-8",
        Some("json" | "map") => "application/json",
        Some("svg") => "image/svg+xml",
        Some("png") => "image/png",
        Some("jpg" | "jpeg") => "image/jpeg",
        Some("gif") => "image/gif",
        Some("webp") => "image/webp",
        Some("avif") => "image/avif",
        Some("ico") => "image/x-icon",
        Some("woff") => "font/woff",
        Some("woff2") => "font/woff2",
        Some("ttf") => "font/ttf",
        Some("txt") => "text/plain; charset=utf-8",
        Some("webmanifest") => "application/manifest+json",
        _ => "application/octet-stream",
    }
}

/// The `Cache-Control` of a console file. Files under `assets/` carry a content hash
/// in their names and never change; every other file is revalidated.
fn cache_control(path: &str) -> &'static str {
    if path.starts_with("assets/") {
        IMMUTABLE
    } else {
        NO_CACHE
    }
}

/// A 200 response with the file's headers and bytes. A HEAD request gets the same
/// headers and no body.
fn file_response(file: &ConsoleFile, head: bool) -> Response {
    let body = if head {
        Body::empty()
    } else {
        Body::from(Bytes::from_static(file.bytes))
    };
    Response::builder()
        .header(header::CONTENT_TYPE, content_type(file.path))
        .header(header::CACHE_CONTROL, cache_control(file.path))
        .header(header::CONTENT_LENGTH, file.bytes.len().to_string())
        .body(body)
        .unwrap_or_else(|_| StatusCode::INTERNAL_SERVER_ERROR.into_response())
}

/// A 405 that names the methods the console answers.
fn method_not_allowed() -> Response {
    let mut response = (StatusCode::METHOD_NOT_ALLOWED, "method not allowed").into_response();
    response
        .headers_mut()
        .insert(header::ALLOW, HeaderValue::from_static("GET, HEAD"));
    response
}

#[cfg(test)]
mod tests {
    use super::*;

    const TABLE: &[ConsoleFile] = &[
        ConsoleFile {
            path: "index.html",
            bytes: b"<!doctype html>",
        },
        ConsoleFile {
            path: "assets/app-abc123.js",
            bytes: b"console.log(1);",
        },
    ];

    #[test]
    fn a_plain_path_is_a_table_key_and_the_root_is_the_empty_key() {
        assert_eq!(
            table_key("/assets/app-abc123.js"),
            Some("assets/app-abc123.js")
        );
        assert_eq!(table_key("/"), Some(""));
    }

    #[test]
    fn a_path_outside_the_allowlist_is_never_a_key() {
        for path in [
            "/../x",
            "/a//b",
            "/a/",
            "//a",
            "/a%20b.js",
            "/a..b.js",
            "/a\\b",
        ] {
            assert_eq!(table_key(path), None, "{path}");
        }
    }

    #[test]
    fn a_key_matches_a_table_path_exactly() {
        assert_eq!(
            find(TABLE, "index.html").map(|file| file.path),
            Some("index.html")
        );
        assert!(find(TABLE, "assets/app").is_none());
        assert!(find(TABLE, "").is_none());
    }

    #[test]
    fn only_the_api_prefix_is_api() {
        assert!(is_api_path("/api"));
        assert!(is_api_path("/api/sites"));
        assert!(!is_api_path("/apiary.js"));
        assert!(!is_api_path("/"));
    }

    #[test]
    fn content_types_follow_the_extension() {
        assert_eq!(content_type("index.html"), "text/html; charset=utf-8");
        assert_eq!(
            content_type("assets/app.MJS"),
            "text/javascript; charset=utf-8"
        );
        assert_eq!(content_type("assets/font.woff2"), "font/woff2");
        assert_eq!(content_type("LICENSE"), "application/octet-stream");
    }

    #[test]
    fn only_assets_are_immutable() {
        assert_eq!(cache_control("assets/app-abc123.js"), IMMUTABLE);
        assert_eq!(cache_control("index.html"), NO_CACHE);
    }
}
